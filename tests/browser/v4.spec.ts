import { expect, test } from '@playwright/test';
import { DEFAULT_CONFIG, FACTION_PRESETS, factionRecord } from '../../src/shared/rules.js';
import { createGame as createLatestGame } from '../../src/sim/world.js';
const createGame: typeof createLatestGame = (config, id, revision = '4.3') => createLatestGame(config, id, revision);
import { applyAction } from '../../src/sim/actions.js';
import { declareWar } from '../../src/sim/wars.js';
import { emptyMetrics } from '../../src/sim/bot.js';

test('V4八方战争目标、占领、信仰危机、灯塔与情报视角', async ({ page }) => {
  const ids = FACTION_PRESETS.map(faction => faction.id);
  const state = createGame({ ...DEFAULT_CONFIG, factionIds: ids, systemCount: 48, models: factionRecord(ids, () => 'grok-4.7') }, 'browser-v4');
  const home = state.systems[0]; home.planets[0].holyCandidate = true;
  applyAction(state, 'aurora', { type: 'establish_religion', args: { planetId: home.planets[0].id, name: '星海圣光', doctrine: '守护人民和圣地', acknowledgePermanent: true } }, 'found');
  const faith = state.factions.aurora.faith!;
  faith.crisis = 75; faith.sites[0].consecratedDay = 0;
  faith.lastChanges = [{ reason: '主圣地失守', amount: 30 }];
  const target = state.systems[1]; target.ownerId = 'umbra'; target.controllerId = 'aurora'; target.base = { hull: 20, disabledUntil: 300 };
  target.planets[0].ownerId = 'umbra'; target.planets[0].population = 2;
  const war = declareWar(state, 'aurora', 'umbra', 'claim', [target.id], '收复预先宣称的边境领土');
  war.goals.aurora[0].heldDays = 200; war.fatigue.aurora = 42; target.occupationWarId = war.id;
  state.factions.verdant.policy!.choice = 'utopia'; state.factions.verdant.beacon = { term: 0, totalDays: 100, suppliedDays: 100, disqualified: false, streak: 3, highest: 2 };
  const snapshot = { state, lastDecisions: null, status: { phase: 'paused', running: false, busy: false, error: null, ai: factionRecord(ids, () => ({ status: '等待决策', requests: 0, actions: 0 })), metrics: factionRecord(ids, emptyMetrics), workers: [] } };
  await page.route('**/api/state', route => route.fulfill({ json: snapshot }));
  await page.routeWebSocket('**/ws', socket => socket.send(JSON.stringify(snapshot)));
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.faction-heading h2')).toHaveCount(8);
  await expect(page.locator('.faith-summary').filter({ hasText: '信仰危机 75.0 / 100' }).first()).toBeVisible();
  await expect(page.locator('.faction-card.verdant')).toContainText('文明灯塔：当前 2 级');
  await expect(page.locator('.civilization-panel')).toContainText('宣称夺取战');
  await expect(page.locator('.war-goal')).toContainText('连续控制 200 / 200 日');
  await page.getByLabel('选择星系', { exact: true }).selectOption(target.id);
  await expect(page.locator('.system-panel')).toContainText('临时占领');
  await expect(page.locator('.system-panel')).toContainText('基地停用剩余300日');
  await page.screenshot({ path: '.data/verification/observer-v4-eight.png', fullPage: true });
  await page.getByLabel('观察势力').selectOption('aurora');
  await expect(page.locator('.faction-heading h2')).toHaveCount(1);
  await page.getByLabel('选择星系', { exact: true }).selectOption(state.factions.verdant.homeSystemId);
  await expect(page.locator('.system-panel .planet-card')).toHaveCount(0);
  await expect(page.locator('.civilization-panel')).toContainText('宣称夺取战');
  await page.getByRole('button', { name: '规则', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('永久国教与信仰危机');
  await expect(page.getByRole('dialog')).toContainText('90%');
  expect(errors).toEqual([]);
});
