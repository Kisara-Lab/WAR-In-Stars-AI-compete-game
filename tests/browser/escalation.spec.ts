import { expect, test } from '@playwright/test';
import { DEFAULT_CONFIG, factionIds, factionRecord } from '../../src/shared/rules.js';
import { createGame as createLatestGame } from '../../src/sim/world.js';
const createGame: typeof createLatestGame = (config, id, revision = '4.3') => createLatestGame(config, id, revision);
import { emptyMetrics } from '../../src/sim/bot.js';
import { relationship, relationKey } from '../../src/shared/diplomacy.js';
import { factionScores } from '../../src/shared/scoring.js';

test('4.1宿敌、征服准备、评分与受限视角', async ({ page }) => {
  const state = createGame(structuredClone(DEFAULT_CONFIG), 'browser-41');
  state.day = 1200; state.round = 12;
  state.rivalries![relationKey('aurora','umbra')] = { factions:['aurora','umbra'],warIds:['first','second','third'],freePeaceDays:0 };
  const relation = relationship(state,'aurora','umbra')!;
  relation.status='peace'; relation.pactUntil=2000;
  state.conquests = [{id:'public-prepare',actor:'aurora',target:'umbra',reason:'公开战略准备',startedDay:1000,readyDay:1360,freePeaceDays:0}];
  state.warAchievements = [{actor:'aurora',target:'umbra',type:'limited',systemId:'s1',day:900,warId:'third'}];
  state.result={winner:'aurora',reason:'score',scores:factionScores(state)};
  const ids=factionIds(state);
  const snapshot={state,lastDecisions:null,status:{phase:'finished',running:false,busy:false,error:null,ai:factionRecord(ids,()=>({status:'等待',requests:0,actions:0})),metrics:factionRecord(ids,emptyMetrics),workers:[]}};
  await page.route('**/api/state',route=>route.fulfill({json:snapshot}));
  await page.routeWebSocket('**/ws',socket=>socket.send(JSON.stringify(snapshot)));
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.civilization-panel .rivalry-status')).toContainText('宿敌 3 / 3');
  await expect(page.locator('.civilization-panel .rivalry-status')).toContainText('条约剩余 800日');
  await expect(page.locator('.civilization-panel .conquest-status')).toContainText('准备剩余 160日');
  await expect(page.locator('.civilization-panel .conquest-status')).toContainText('最早可宣战第2000日');
  await page.locator('.result-breakdown > summary').click();
  await page.locator('.result-breakdown .score-detail').first().locator('summary').click();
  await expect(page.locator('.result-breakdown')).toContainText('非领土目标 50 / 500');
  await expect(page.locator('.result-breakdown')).toContainText('权重0.5');
  await page.screenshot({path:'.data/verification/v41-war-entry.png',fullPage:true});
  await page.getByLabel('观察势力').selectOption('verdant');
  await expect(page.locator('.rivalry-status')).toHaveCount(0);
  await expect(page.locator('.conquest-status')).toHaveCount(0);
  await page.getByRole('button',{name:'规则',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('4.1 宿敌与公开征服准备');
  expect(errors).toEqual([]);
});
