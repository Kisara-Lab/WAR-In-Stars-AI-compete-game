import { DEFAULT_CONFIG } from '../../src/shared/rules.js';
import { mkdir } from 'node:fs/promises';
import { expect, test } from '@playwright/test';

test('观察界面可创建比赛、查看星系、推进整局和复盘', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.request.post('/api/matches', { data: { ...DEFAULT_CONFIG, controller: 'scripted' } });
  await page.goto('/');
  await expect(page.getByText('战场已连接')).toBeVisible();
  await expect(page.locator('.faction-heading h2')).toHaveCount(4);
  await expect(page.locator('canvas')).toBeVisible();
  await mkdir('.data/verification', { recursive: true });
  await page.screenshot({ path: '.data/verification/observer-galaxy.png', fullPage: true });
  await page.getByRole('button', { name: '◎ 单星系' }).click();
  await expect(page.getByRole('img', { name: '天枢-1星系视图' })).toBeVisible();
  await page.screenshot({ path: '.data/verification/observer-system.png', fullPage: true });
  await page.getByRole('button', { name: '＋ 新比赛' }).click();
  await page.getByLabel('控制方式').selectOption('scripted');
  await page.getByLabel('最大轮数').fill('6');
  await page.getByLabel('地图种子').fill('browser-verification');
  await page.getByRole('button', { name: '创建比赛', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: '▷ 单轮推进' }).click();
  await expect(page.locator('.match-clock strong')).toHaveText('001');
  await expect(page.getByRole('button', { name: '继续比赛', exact: false })).toBeEnabled();
  await page.getByRole('button', { name: '继续比赛', exact: false }).click();
  await expect(page.locator('.result-banner')).toBeVisible();
  await expect(page.locator('.match-clock strong')).toHaveText('006');
  await page.getByRole('button', { name: '外交关系', exact: true }).click();
  await expect(page.getByRole('table', { name: '外交关系矩阵' })).toBeVisible();
  await expect(page.locator('.relation-cell')).toHaveCount(12);
  await page.getByRole('button', { name: 'AI 决策记录', exact: true }).click();
  await expect(page.locator('.decision-column')).toHaveCount(4);
  await expect(page.locator('.decision-column').first()).toContainText('脚本演示');
  await page.getByRole('button', { name: '存档 / 复盘', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.locator('input[type=range]').fill('0');
  await page.getByRole('button', { name: '查看历史', exact: true }).click();
  await expect(page.locator('.replay-bar')).toContainText('历史第 0 轮');
  await page.getByRole('button', { name: '下一轮', exact: true }).click();
  await expect(page.locator('.replay-bar')).toContainText('历史第 1 轮');
  await page.getByRole('button', { name: '从这里继续', exact: true }).click();
  await expect(page.locator('.replay-bar')).toHaveCount(0);
  await expect(page.locator('.match-clock strong')).toHaveText('001');
  await page.getByRole('button', { name: '规则', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('星际战场规则');
  await expect(page.getByRole('dialog')).toContainText('无畏舰');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '＋ 新比赛' }).click();
  await page.getByLabel('AI 势力数量').selectOption('8');
  await page.getByLabel('最大轮数').fill('1');
  await page.getByRole('button', { name: '创建比赛', exact: true }).click();
  await expect(page.locator('.faction-heading h2')).toHaveCount(8);
  await page.getByRole('button', { name: '▷ 单轮推进' }).click();
  await expect(page.locator('.result-banner')).toBeVisible();
  await expect(page.locator('.result-score > span')).toHaveCount(8);
  expect(errors).toEqual([]);
});
