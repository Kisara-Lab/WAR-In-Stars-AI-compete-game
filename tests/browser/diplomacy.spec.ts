import { expect, test } from '@playwright/test';
import { DEFAULT_CONFIG, FACTION_PRESETS, factionRecord } from '../../src/shared/rules.js';
import { createGame as createLatestGame } from '../../src/sim/world.js';
const createGame: typeof createLatestGame = (config, id, revision = '4.3') => createLatestGame(config, id, revision);
import { relationship } from '../../src/shared/diplomacy.js';
import { emptyMetrics } from '../../src/sim/bot.js';

test('八方外交矩阵、单向通行、条约倒计时与观察势力', async ({ page }) => {
  const ids = FACTION_PRESETS.map(faction => faction.id);
  const state = createGame({ ...DEFAULT_CONFIG, factionIds: ids, systemCount: 48, models: factionRecord(ids, () => 'grok-4.7') });
  const relation = relationship(state, 'aurora', 'umbra')!;
  relation.status = 'peace'; relation.confirmed = ['aurora', 'umbra']; relation.pactUntil = 1080; relation.access.aurora = true;
  const negotiating = relationship(state, 'cobalt', 'verdant')!;
  negotiating.status = 'war'; negotiating.offers.cobalt = { createdRound: 0, expiresDay: 300 };
  const snapshot = { state, lastDecisions: null, status: { phase: 'ready', running: false, busy: false, error: null, ai: factionRecord(ids, () => ({ status: '等待决策', requests: 0, actions: 0 })), metrics: factionRecord(ids, emptyMetrics), workers: [] } };
  await page.route('**/api/state', route => route.fulfill({ json: snapshot }));
  await page.routeWebSocket('**/ws', socket => socket.send(JSON.stringify(snapshot)));
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.faction-heading h2')).toHaveCount(8);
  await page.getByLabel('观察势力').selectOption('aurora');
  await page.getByRole('button', { name: '外交关系', exact: true }).click();
  await expect(page.locator('.relation-cell')).toHaveCount(56);
  const cells = page.locator('.relation-cell').filter({ hasText: '互不侵犯' });
  await expect(cells).toHaveCount(2);
  await expect(cells.filter({ hasText: '允许访客进入' })).toHaveCount(1);
  await expect(cells.filter({ hasText: '边境关闭' })).toHaveCount(1);
  await cells.first().click();
  await expect(page.locator('.diplomacy-detail')).toContainText('剩余 1080 日');
  await expect(page.locator('.relation-cell.war')).toHaveCount(0);
  await page.getByLabel('观察势力').selectOption('');
  await page.locator('.relation-cell.war').first().click();
  await expect(page.locator('.diplomacy-detail')).toContainText('等待翠星联邦');
  await page.screenshot({ path: '.data/verification/observer-diplomacy-eight.png', fullPage: true });
  await page.getByRole('button', { name: '＋ 新比赛' }).click();
  await expect(page.getByLabel('AI 势力数量')).toHaveValue('8');
  await page.getByLabel('AI 势力数量').selectOption('5');
  await expect(page.getByLabel('星系数量')).toHaveValue('50');
  await expect(page.getByRole('dialog').getByRole('combobox')).toHaveCount(7);
  expect(errors).toEqual([]);
});
